#!/usr/bin/env python3
"""Generate the installer's bundled container helpers from their canonical sources."""
import json
from pathlib import Path
import subprocess

root = Path(__file__).resolve().parents[1]
assets = {p.name: p.read_text() for p in sorted((root / 'scripts/lib').glob('*.py'))}
assets['dcore.der'] = (root / 'secureboot/dcore.der').read_bytes().hex()
output = '// Code generated by scripts/embed-installer-assets.py; DO NOT EDIT.\npackage main\n\nvar bundledAssets = map[string]string{\n'
for name, value in assets.items():
    output += '\t' + json.dumps(name) + ': ' + json.dumps(value, ensure_ascii=False) + ',\n'
output += '}\n'
(root / 'installer/assets_generated.go').write_text(output)
subprocess.run(['gofmt', '-w', str(root / 'installer/assets_generated.go')], check=True)
